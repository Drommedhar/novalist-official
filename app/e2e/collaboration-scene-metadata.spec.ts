import { expect, test } from '@playwright/test'
import { join } from 'node:path'
import { dismissTour, launchApp, seedBook, type Harness } from './harness'

test('scene metadata keeps focus locks across inspector and outliner controls', async () => {
  const participants: Harness[] = []
  try {
    const owner = await launchApp('nl-scene-metadata-owner-')
    participants.push(owner)
    const state = await seedBook(owner, { Opening: ['Arrival'] })
    await dismissTour(owner.page)
    const chapter = state.chapters.find(chapter => chapter.title === 'Opening')!
    const scene = chapter.scenes[0]
    await owner.rpc('entities/create', ['character', 'Scene companion'])
    await owner.rpc('scenes/write', [chapter.guid, scene.id, '<p>Scene companion waited by the gate.</p>', 'Scene companion waited by the gate.'])
    await owner.rpc('manuscriptProps/setDefinitions', [[{ key: 'weather', label: 'Weather', type: 'String', scope: 'Scene', enumOptions: [], showInOutliner: true }]])
    await owner.rpc('manuscriptProps/setSceneValue', [scene.id, 'weather', 'Fog'])
    await owner.rpc('collaboration/peer/host', ['127.0.0.1', 0, 'Owner'])
    const link = await owner.rpc<string>('collaboration/invite', [new Date(Date.now() + 60_000).toISOString()])
    const guest = await launchApp('nl-scene-metadata-guest-')
    participants.push(guest)
    await dismissTour(guest.page)
    await guest.rpc('collaboration/peer/join', [link, join(guest.workDir, 'Joined'), 'Guest'])
    for (const h of participants) {
      await h.page.evaluate(() => document.querySelector<HTMLButtonElement>('[data-collaboration-trigger][aria-expanded="false"]')?.click())
      await expect(h.page.getByText('Connected to the shared project.', { exact: true })).toBeVisible()
      await h.page.evaluate(async ({ chapter, scene }) => {
        await window.novalistStores.project.getState().openScene(chapter, scene)
        window.novalistStores.shell.getState().setInspectorTab('notes')
      }, { chapter: chapter.guid, scene: scene.id })
      await expect(h.page.locator('#inspector-rel-amount')).toBeVisible()
    }
    const first = owner.page.locator('#inspector-rel-amount')
    const second = guest.page.locator('#inspector-rel-amount')
    await first.focus()
    await expect(first).not.toHaveAttribute('readonly', '')
    await second.focus()
    await expect(second).toHaveAttribute('readonly', '')
    await first.fill('2')
    const units = owner.page.locator('.inspector .notes-dock-relative select')
    await units.focus()
    await units.selectOption('Days')
    await expect(second).toHaveAttribute('readonly', '')
    await owner.page.locator('#inspector-mode').focus()
    await expect(second).toHaveValue('2')
    await expect(guest.page.locator('.inspector .notes-dock-relative select')).toHaveValue('Days')
    const ownerMode = owner.page.locator('#inspector-mode')
    const guestMode = guest.page.locator('#inspector-mode')
    await guestMode.focus()
    await expect(guestMode).toHaveAttribute('aria-disabled', 'true')
    await ownerMode.selectOption('parallel')
    await ownerMode.blur()
    await expect(guestMode).toHaveValue('parallel')
    const ownerStrand = owner.page.locator('.inspector').getByLabel('Strand', { exact: true })
    const guestStrand = guest.page.locator('.inspector').getByLabel('Strand', { exact: true })
    await ownerStrand.focus()
    await expect(ownerStrand).not.toHaveAttribute('readonly', '')
    await guestStrand.focus()
    await expect(guestStrand).toHaveAttribute('readonly', '')
    await ownerStrand.fill('Elsewhere')
    await ownerStrand.blur()
    await expect(guestStrand).toHaveValue('Elsewhere')
    const ownerCast = owner.page.locator('.inspector .scene-cast input')
    const guestCast = guest.page.locator('.inspector .scene-cast input')
    await ownerCast.focus()
    await expect(ownerCast).not.toHaveAttribute('readonly', '')
    await guestCast.focus()
    await expect(guestCast).toHaveAttribute('readonly', '')
    await ownerCast.fill('Scene companion')
    await owner.page.locator('.inspector .scene-cast-match').click()
    await first.focus()
    await expect(guest.page.locator('.inspector .scene-cast-name')).toHaveText('Scene companion')
    await owner.page.locator('.inspector .scene-cast-star').click()
    await expect(guest.page.locator('.inspector .scene-cast-chip')).toHaveClass(/focus/)
    for (const h of participants) await h.page.evaluate(() => window.novalistStores.shell.getState().setInspectorTab('context'))
    const ownerConflict = owner.page.getByPlaceholder('Conflict', { exact: true })
    const guestConflict = guest.page.getByPlaceholder('Conflict', { exact: true })
    await ownerConflict.focus()
    await expect(ownerConflict).not.toHaveAttribute('readonly', '')
    await guestConflict.focus()
    await expect(guestConflict).toHaveAttribute('readonly', '')
    await ownerConflict.fill('The gate is sealed')
    await ownerConflict.blur()
    await expect(guestConflict).toHaveValue('The gate is sealed')
    const ownerIntensity = owner.page.locator('.ctx-intensity-input')
    const guestIntensity = guest.page.locator('.ctx-intensity-input')
    await ownerIntensity.focus()
    await expect(ownerIntensity).not.toHaveAttribute('readonly', '')
    await guestIntensity.focus()
    await expect(guestIntensity).toHaveAttribute('readonly', '')
    await ownerIntensity.fill('7')
    await ownerIntensity.blur()
    await expect(guestIntensity).toHaveValue('7')
    const ownerTags = owner.page.getByPlaceholder('Comma-separated tags')
    const guestTags = guest.page.getByPlaceholder('Comma-separated tags')
    await ownerTags.focus()
    await expect(ownerTags).not.toHaveAttribute('readonly', '')
    await ownerTags.fill('')
    await ownerTags.pressSequentially('tension, mystery')
    await expect(ownerTags).toHaveValue('tension, mystery')
    await ownerTags.blur()
    await expect(guestTags).toHaveValue('tension, mystery')
    const ownerPov = owner.page.locator('.ctx-pov')
    const guestPov = guest.page.locator('.ctx-pov')
    await ownerPov.focus()
    await expect(ownerPov).toHaveAttribute('aria-disabled', 'false')
    await guestPov.focus()
    await expect(guestPov).toHaveAttribute('aria-disabled', 'true')
    await ownerPov.selectOption('Scene companion')
    await ownerPov.blur()
    await expect(guestPov).toHaveValue('Scene companion')
    for (const h of participants) await h.page.evaluate(() => window.novalistStores.shell.getState().setInspectorTab('notes'))
    const ownerWeather = owner.page.locator('.inspector').getByLabel('Weather', { exact: true })
    const guestWeather = guest.page.locator('.inspector').getByLabel('Weather', { exact: true })
    await ownerWeather.focus()
    await expect(ownerWeather).not.toHaveAttribute('readonly', '')
    await guestWeather.focus()
    await expect(guestWeather).toHaveAttribute('readonly', '')
    await ownerWeather.fill('Sun')
    await ownerWeather.blur()
    await expect(guestWeather).toHaveValue('Sun')
    for (const h of participants) {
      await h.page.evaluate(() => window.novalistStores.shell.getState().setMainView('manuscript'))
      await h.page.getByRole('button', { name: 'Outliner', exact: true }).click()
    }
    const ownerTarget = owner.page.locator('.outliner-target').first()
    const guestTarget = guest.page.locator('.outliner-target').first()
    await ownerTarget.focus()
    await expect(ownerTarget).not.toHaveAttribute('readonly', '')
    await guestTarget.focus()
    await expect(guestTarget).toHaveAttribute('readonly', '')
    await ownerTarget.fill('1200')
    await ownerTarget.blur()
    await expect(guestTarget).toHaveValue('1200')
    const ownerColumn = owner.page.locator('.outliner').getByLabel('Weather', { exact: true })
    const guestColumn = guest.page.locator('.outliner').getByLabel('Weather', { exact: true })
    await ownerColumn.focus()
    await expect(ownerColumn).not.toHaveAttribute('readonly', '')
    await guestColumn.focus()
    await expect(guestColumn).toHaveAttribute('readonly', '')
    await ownerColumn.fill('Rain')
    await ownerColumn.blur()
    await expect(guestColumn).toHaveValue('Rain')
    const ownerOutlinerPov = owner.page.locator('.outliner').getByPlaceholder('POV', { exact: true })
    const guestOutlinerPov = guest.page.locator('.outliner').getByPlaceholder('POV', { exact: true })
    await ownerOutlinerPov.focus()
    await expect(ownerOutlinerPov).not.toHaveAttribute('readonly', '')
    await guestOutlinerPov.focus()
    await expect(guestOutlinerPov).toHaveAttribute('readonly', '')
    await ownerOutlinerPov.fill('A new narrator')
    await ownerOutlinerPov.blur()
    await expect(guestOutlinerPov).toHaveValue('A new narrator')
  } finally {
    for (const h of participants.reverse()) await h.close()
  }
})
