import { expect, test } from '@playwright/test'
import { join } from 'node:path'
import { dismissTour, launchApp, seedBook, selectCodexTab, type Harness } from './harness'

test('Codex policy controls show the focused writer and preserve independent section settings', async () => {
  const apps: Harness[] = []
  try {
    const owner = await launchApp('nl-policy-owner-')
    apps.push(owner)
    await seedBook(owner, { Chapter: ['Scene'] })
    const entity = await owner.rpc<{ id: string }>('entities/create', ['character', 'Mira'])
    await owner.rpc('entities/updateLists', ['character', entity.id, null, [{ id: 'secret', title: 'Secret', content: 'Keep this prose.' }], null])
    await owner.rpc('collaboration/peer/host', ['127.0.0.1', 0, 'Morgan'])
    const invitation = await owner.rpc<string>('collaboration/invite', [new Date(Date.now() + 60_000).toISOString()])
    const guest = await launchApp('nl-policy-guest-')
    apps.push(guest)
    await guest.rpc('collaboration/peer/join', [invitation, join(guest.workDir, 'Joined'), 'Alex'])
    for (const app of apps) {
      await dismissTour(app.page)
      await app.page.evaluate(() => document.querySelector<HTMLButtonElement>('[data-collaboration-trigger][aria-expanded="false"]')?.click())
      await expect(app.page.getByRole('button', { name: 'End this session', exact: true })).toBeVisible()
      await app.page.evaluate(async id => {
        window.novalistStores.shell.getState().setMainView('codex')
        await window.novalistStores.codex.getState().setType('character')
        await window.novalistStores.codex.getState().select(id)
      }, entity.id)
      await selectCodexTab(app.page, 'details')
      await app.page.getByText('What AI may see of this entry', { exact: true }).click()
      await app.page.getByText('What readers may see', { exact: true }).click()
      await app.page.getByText('How this name is detected in prose', { exact: true }).click()
    }
    const ownerMatch = owner.page.getByRole('checkbox', { name: 'Match only this exact capitalisation', exact: true })
    const guestMatch = guest.page.getByRole('checkbox', { name: 'Match only this exact capitalisation', exact: true })
    await ownerMatch.focus()
    await expect(ownerMatch).toHaveAttribute('aria-disabled', 'false')
    await ownerMatch.check()
    await guestMatch.focus()
    await expect(guest.page.getByRole('status', { name: 'Morgan is editing this field.', exact: true })).toBeVisible()
    await ownerMatch.blur()
    await expect(guestMatch).toHaveAttribute('aria-disabled', 'false')
    await expect(guestMatch).toBeChecked()
    await guestMatch.blur()
    const exclusion = owner.page.getByPlaceholder('rose garden', { exact: true })
    await exclusion.focus()
    await expect(exclusion).not.toHaveAttribute('readonly', '')
    await exclusion.fill('Mira valley')
    const plural = guest.page.getByRole('checkbox', { name: 'Also match the plural', exact: true })
    await plural.focus()
    await expect(plural).toHaveAttribute('aria-disabled', 'false')
    await plural.check()
    await plural.blur()
    await exclusion.press('Enter')
    await exclusion.blur()
    await expect.poll(() => guest.rpc('entities/getMatchSettings', ['character', entity.id])).toMatchObject({
      caseSensitive: true, matchPlurals: true, exclusions: ['Mira valley']
    })
    const ownerAi = owner.page.getByRole('radio', { name: 'Always', exact: true })
    const guestAi = guest.page.getByRole('radio', { name: 'Never', exact: true })
    await owner.page.bringToFront()
    await ownerAi.focus()
    await expect(ownerAi).toHaveAttribute('aria-disabled', 'false')
    await ownerAi.check()
    await guest.page.bringToFront()
    await guestAi.focus()
    await expect(guest.page.getByRole('status', { name: 'Morgan is editing this field.', exact: true })).toBeVisible()
    await expect(guestAi).not.toBeChecked()
    const ownerReader = owner.page.getByRole('checkbox', { name: 'Keep this entry from readers entirely', exact: true })
    await owner.page.bringToFront()
    await ownerReader.focus()
    await expect(ownerReader).toBeFocused()
    await expect.poll(async () => (await guest.rpc<{ inclusion: string }>('entities/getAiPolicy', ['character', entity.id])).inclusion).toBe('Always')
    await expect(guestAi).toHaveAttribute('aria-disabled', 'false')
    await guest.page.bringToFront()
    await guestAi.check()
    await guestAi.blur()
    await owner.page.bringToFront()
    await ownerReader.check()
    await ownerReader.blur()
    await expect.poll(async () => (await owner.rpc<{ inclusion: string }>('entities/getAiPolicy', ['character', entity.id])).inclusion).toBe('Never')
    await expect.poll(async () => (await guest.rpc<{ hidden: boolean }>('entities/getReaderPolicy', ['character', entity.id])).hidden).toBe(true)
    expect((await guest.rpc<{ sections: { content: string }[] }>('entities/get', ['character', entity.id])).sections[0].content).toBe('Keep this prose.')
    await guest.page.locator('.codex-row').filter({ hasText: 'Mira' }).click({ button: 'right' })
    await guest.page.getByRole('menuitem', { name: 'Settle this entry (refuse edits)', exact: true }).click()
    await expect.poll(async () => (await owner.rpc<{ locked: boolean }>('entities/get', ['character', entity.id])).locked).toBe(true)
    await owner.page.locator('.codex-row').filter({ hasText: 'Mira' }).click({ button: 'right' })
    await owner.page.getByRole('menuitem', { name: 'Unsettle this entry', exact: true }).click()
    await expect.poll(async () => (await guest.rpc<{ locked?: boolean }>('entities/get', ['character', entity.id])).locked ?? false).toBe(false)
  } finally { for (const app of apps.reverse()) await app.close() }
})
