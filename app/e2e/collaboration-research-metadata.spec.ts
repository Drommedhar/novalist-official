import { expect, test } from '@playwright/test'
import { join } from 'node:path'
import { dismissTour, launchApp, seedBook, type Harness } from './harness'

test('Research metadata locks, reciprocal links and file-to-prose transitions work between writers', async () => {
  const participants: Harness[] = []
  try {
    const owner = await launchApp('novalist-metadata-owner-')
    participants.push(owner)
    await seedBook(owner, { Opening: ['Arrival'] })
    await dismissTour(owner.page)
    const character = await owner.rpc<{ id: string }>('entities/create', ['character', 'Research subject'])
    const [note] = await owner.rpc<{ id: string }[]>('research/save', [null, 'Shared source', 'Note', 'Original source.', [], []])
    await owner.rpc('manuscriptProps/setDefinitions', [[{ key: 'source', label: 'Source location', type: 'String', scope: 'Research', enumOptions: [], showInOutliner: false }]])
    await owner.rpc('manuscriptProps/setResearchValue', [note.id, 'source', 'Archive'])
    const related = (await owner.rpc<{ id: string; title: string }[]>('research/save', [null, 'Related source', 'Note', 'Related evidence.', [], []])).find(item => item.title === 'Related source')!
    await owner.rpc('collaboration/peer/host', ['127.0.0.1', 0, 'Owner'])
    const link = await owner.rpc<string>('collaboration/invite', [new Date(Date.now() + 60_000).toISOString()])
    const guest = await launchApp('novalist-metadata-guest-')
    participants.push(guest)
    await dismissTour(guest.page)
    await guest.rpc('collaboration/peer/join', [link, join(guest.workDir, 'Joined'), 'Guest'])
    for (const h of participants) {
      await h.page.evaluate(() => window.novalistStores.shell.getState().openSettings('collaboration'))
      await expect(h.page.getByText('Connected to the shared project.', { exact: true })).toBeVisible()
      await h.page.evaluate(id => window.novalistStores.shell.getState().navigateToResearch(id), note.id)
      await expect(h.page.locator('.research-title')).toHaveValue('Shared source')
    }
    const first = owner.page.locator('.research-title')
    const second = guest.page.locator('.research-title')
    await first.focus()
    await expect(first).not.toHaveAttribute('readonly', '')
    await second.focus()
    await expect(second).toHaveAttribute('readonly', '')
    await expect(guest.page.getByText('Owner is editing this field.', { exact: true })).toBeVisible()
    await first.fill('Title from the owner')
    await first.blur()
    await expect(first).toHaveAttribute('readonly', '')
    await expect(second).toHaveValue('Title from the owner')
    await second.blur()
    await second.focus()
    await expect(second).not.toHaveAttribute('readonly', '')
    await second.fill('Title from the invited writer')
    await second.blur()
    await expect(first).toHaveValue('Title from the invited writer')
    await expect(owner.page.locator('.research-content .cm-content')).toHaveText('Original source.')
    for (const h of participants) await h.page.locator('.research-metadata > summary').click()
    const ownerTag = owner.page.getByPlaceholder('Add tag…')
    const guestTag = guest.page.getByPlaceholder('Add tag…')
    await ownerTag.focus()
    await expect(ownerTag).not.toHaveAttribute('readonly', '')
    await guestTag.focus()
    await expect(guestTag).toHaveAttribute('readonly', '')
    await ownerTag.fill('History')
    await ownerTag.press('Enter')
    await owner.page.getByLabel('Status', { exact: true }).focus()
    await expect(guest.page.locator('.research-tag').filter({ hasText: 'History' })).toHaveCount(1)
    const ownerStatus = owner.page.getByLabel('Status', { exact: true })
    const guestStatus = guest.page.getByLabel('Status', { exact: true })
    await guestStatus.focus()
    await expect(guestStatus).toHaveAttribute('aria-disabled', 'true')
    await ownerStatus.selectOption('Open')
    await ownerStatus.blur()
    await expect(guestStatus).toHaveValue('Open')
    const rating = owner.page.locator('.research-rating button').nth(3)
    await rating.focus()
    await expect(rating).toHaveAttribute('aria-disabled', 'false')
    await rating.click()
    await rating.blur()
    await expect(guest.page.locator('.research-rating button').nth(3)).toHaveAttribute('aria-pressed', 'true')
    const entityPicker = owner.page.getByLabel('Link an entry...', { exact: true })
    const guestPicker = guest.page.getByLabel('Link an entry...', { exact: true })
    await entityPicker.focus()
    await expect(entityPicker).toHaveAttribute('aria-disabled', 'false')
    await guestPicker.focus()
    await expect(guestPicker).toHaveAttribute('aria-disabled', 'true')
    await entityPicker.selectOption(character.id)
    await entityPicker.blur()
    await expect(guest.page.locator('.research-tag').filter({ hasText: 'Research subject' })).toHaveCount(1)
    const ownerSource = owner.page.getByLabel('Source location', { exact: true })
    const guestSource = guest.page.getByLabel('Source location', { exact: true })
    await ownerSource.focus()
    await expect(ownerSource).not.toHaveAttribute('readonly', '')
    await guestSource.focus()
    await expect(guestSource).toHaveAttribute('readonly', '')
    await ownerSource.fill('Library')
    await ownerSource.blur()
    await expect(guestSource).toHaveValue('Library')
    const ownerRelated = owner.page.locator('select').filter({ has: owner.page.locator('option', { hasText: 'Link another item...' }) })
    const guestRelated = guest.page.locator('select').filter({ has: guest.page.locator('option', { hasText: 'Link another item...' }) })
    await ownerRelated.focus()
    await expect(ownerRelated).toHaveAttribute('aria-disabled', 'false')
    await guestRelated.focus()
    await expect(guestRelated).toHaveAttribute('aria-disabled', 'true')
    await ownerRelated.selectOption(related.id)
    await ownerRelated.blur()
    await expect(guest.page.locator('.research-related-open')).toHaveText('Related source')
    expect((await guest.rpc<{ id: string; relatedIds: string[] }[]>('research/list')).find(item => item.id === related.id)?.relatedIds).toContain(note.id)
    const ownerType = owner.page.locator('select').filter({ has: owner.page.locator('option[value="File"]') })
    const guestType = guest.page.locator('select').filter({ has: guest.page.locator('option[value="File"]') })
    await ownerType.focus()
    await expect(ownerType).toHaveAttribute('aria-disabled', 'false')
    await guestType.focus()
    await expect(guestType).toHaveAttribute('aria-disabled', 'true')
    await ownerType.selectOption('File')
    await ownerType.blur()
    await expect(guestType).toHaveValue('File')
    const ownerContent = owner.page.locator('.research-content .cm-content')
    const guestContent = guest.page.locator('.research-content .cm-content')
    await expect(ownerContent).toHaveAttribute('aria-readonly', 'true')
    await ownerContent.focus()
    await expect(ownerContent).toHaveAttribute('aria-readonly', 'false')
    await guestContent.focus()
    await expect(guestContent).toHaveAttribute('aria-readonly', 'true')
    await ownerContent.fill('Reference path')
    await ownerContent.blur()
    await expect(guestContent).toHaveText('Reference path')
    await guestType.blur()
    await guestContent.blur()
    await ownerType.focus()
    await expect(ownerType).toHaveAttribute('aria-disabled', 'false')
    await ownerType.selectOption('Note')
    await ownerType.blur()
    await expect(guestType).toHaveValue('Note')
    await ownerContent.fill('Shared prose again')
    await expect(guestContent).toHaveText('Shared prose again')
    await ownerTag.focus()
    await expect(ownerTag).not.toHaveAttribute('readonly', '')
    await ownerTag.fill('inbox')
    await ownerTag.press('Enter')
    await ownerTag.blur()
    await expect(guest.page.getByRole('button', { name: 'Keep as research note', exact: true })).toBeVisible()
    await ownerTag.focus()
    await expect(ownerTag).not.toHaveAttribute('readonly', '')
    await guest.page.getByRole('button', { name: 'Keep as research note', exact: true }).click()
    await expect(guest.page.getByText('Owner is editing this field.', { exact: true })).toBeVisible()
    await ownerTag.blur()
    await guest.page.getByRole('button', { name: 'Keep as research note', exact: true }).click()
    await expect(owner.page.getByRole('button', { name: 'Keep as research note', exact: true })).toHaveCount(0)
    await expect(owner.page.locator('.research-tag').filter({ hasText: 'History' })).toHaveCount(1)
  } finally {
    for (const participant of participants.reverse()) await participant.close()
  }
})
