test('Map layer branches collapse smoothly and retain nested expansion choices', async () => {
  const h = await launchApp('nl-map-tree-motion-')
  try {
    await h.page.emulateMedia({ reducedMotion: 'no-preference' })
    await seedBook(h, { Opening: ['Arrival'] })
    await h.rpc('maps/create', ['Coast'])
    await dismissTour(h.page)
    await h.page.evaluate(() => window.novalistStores.shell.getState().setMainView('maps'))
    const tree = h.page.locator('.map-layer-tree')
    const rows = tree.locator('.map-layer-row')
    await h.page.locator('.map-panel-add').click()
    await expect(rows).toHaveCount(1)
    await rows.first().locator('.map-layer-actions button').nth(2).click()
    await expect(rows).toHaveCount(2)
    await rows.nth(1).locator('.map-layer-actions button').nth(2).click()
    await expect(rows).toHaveCount(3)
    await expect.poll(() => tree.evaluate(element => element.getAnimations({ subtree: true }).length)).toBe(0)
    const motion = await holdMotion(h.page, '.map-layer-tree')
    const descendant = rows.nth(2).locator('..')
    const expandedHeight = await descendant.evaluate(element => element.getBoundingClientRect().height)
    await rows.nth(1).locator('.map-layer-twisty').click()
    const closing = tree.locator('[data-motion-presence="closing"][inert]')
    await expect(closing).toHaveCount(1)
    await motion.evaluate(control => control.middle())
    const height = await descendant.evaluate(element => element.getBoundingClientRect().height)
    expect(height).toBeGreaterThan(0)
    expect(height).toBeLessThan(expandedHeight)
    await expectFade(motion)
    await expect(rows).toHaveCount(2)
    await rows.first().locator('.map-layer-twisty').click()
    await expect(closing).toHaveCount(2)
    await expectFade(motion)
    await expect(rows).toHaveCount(1)
    await rows.first().locator('.map-layer-twisty').click()
    await expectFade(motion)
    await expect(rows).toHaveCount(2)
    await rows.nth(1).locator('.map-layer-twisty').click()
    await expectFade(motion)
    await expect(rows).toHaveCount(3)
    await motion.evaluate(control => control.stop())
    await h.page.emulateMedia({ reducedMotion: 'reduce' })
    await rows.first().locator('.map-layer-twisty').click()
    await expect(rows).toHaveCount(1)
    expect(await tree.evaluate(element => element.getAnimations({ subtree: true }).length)).toBe(0)
  } finally {
    await h.close()
  }
})
