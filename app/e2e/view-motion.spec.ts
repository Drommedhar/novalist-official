import { expect, test } from '@playwright/test'
import { dismissTour, launchApp, seedBook } from './harness'
import { holdMotion } from './motion'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

async function expectFade(motion: Awaited<ReturnType<typeof holdMotion>>): Promise<void> {
  expect((await motion.evaluate(control => control.details()))
    .some(animation => animation.fading && animation.duration > 0 && animation.duration <= 200)).toBe(true)
  await motion.evaluate(control => control.finish())
}

test('Codex selection and detail tabs fade without remounting fields or animating typing', async () => {
  const h = await launchApp('nl-codex-motion-')
  try {
    await h.page.emulateMedia({ reducedMotion: 'no-preference' })
    await seedBook(h, { Opening: ['Arrival'] })
    const first = await h.rpc<{ id: string }>('entities/create', ['character', 'Mira'])
    await h.rpc('entities/create', ['character', 'Tomas'])
    await dismissTour(h.page)
    await h.page.evaluate(async id => {
      window.novalistStores.shell.getState().setMainView('codex')
      await window.novalistStores.codex.getState().select(id)
    }, first.id)
    const detail = h.page.locator('.codex-detail')
    await expect(detail.locator('h2')).toHaveText('Mira')
    await expect.poll(() => detail.evaluate(element => element.getAnimations().length)).toBe(0)
    const originalDetail = await detail.evaluateHandle(element => element)
    const motion = await holdMotion(h.page, '.codex-detail')
    await h.page.locator('.codex-row').filter({ hasText: 'Tomas' }).click()
    await expect(detail.locator('h2')).toHaveText('Tomas')
    await expectFade(motion)
    const name = detail.getByRole('textbox', { name: 'Name', exact: true })
    const originalField = await name.evaluateHandle(element => element)
    await detail.locator('.codex-entry-tabs').getByRole('button', { name: 'Story', exact: true }).click()
    await expect(detail).toHaveAttribute('data-detail-tab', 'story')
    await expectFade(motion)
    await detail.locator('.codex-entry-tabs').getByRole('button', { name: 'Overview', exact: true }).click()
    await expectFade(motion)
    expect(await originalDetail.evaluate(element => element.isConnected)).toBe(true)
    expect(await originalField.evaluate(element => element.isConnected)).toBe(true)
    await name.fill('Tomas Vance')
    await expect(name).toBeFocused()
    expect((await motion.evaluate(control => control.details())).some(animation => animation.fading)).toBe(false)
    await motion.evaluate(control => control.stop())
    await h.page.emulateMedia({ reducedMotion: 'reduce' })
    await detail.locator('.codex-entry-tabs').getByRole('button', { name: 'Details', exact: true }).click()
    await expect(detail).toHaveAttribute('data-detail-tab', 'details')
    expect(await detail.evaluate(element => element.getAnimations({ subtree: true }).length)).toBe(0)
  } finally {
    await h.close()
  }
})

test('Research selection and scratchpad tabs fade while preserving and saving the note', async () => {
  const h = await launchApp('nl-research-motion-')
  try {
    await h.page.emulateMedia({ reducedMotion: 'no-preference' })
    await seedBook(h, { Opening: ['Arrival'] })
    await h.rpc('research/save', [null, 'First source', 'Note', 'First note.', [], []])
    await h.rpc('research/save', [null, 'Second source', 'Note', 'Second note.', [], []])
    await dismissTour(h.page)
    await h.page.evaluate(() => window.novalistStores.shell.getState().setMainView('research'))
    const view = h.page.locator('.research-view')
    await view.locator('.codex-row').filter({ hasText: 'First source' }).click()
    const title = view.getByRole('textbox', { name: 'Title', exact: true })
    await expect(title).toHaveValue('First source')
    await expect.poll(() => view.evaluate(element => element.getAnimations({ subtree: true }).length)).toBe(0)
    const motion = await holdMotion(h.page, '.research-view')
    await view.locator('.codex-row').filter({ hasText: 'Second source' }).click()
    await expect(title).toHaveValue('Second source')
    await expectFade(motion)
    const originalEditor = await title.evaluateHandle(element => element)
    await title.fill('Edited second source')
    expect((await motion.evaluate(control => control.details())).some(animation => animation.fading)).toBe(false)
    const tabs = view.locator('.codex-tabs .codex-tab')
    await tabs.nth(1).click()
    await expect(view.locator('.research-scratchpad')).toBeVisible()
    await expectFade(motion)
    await tabs.nth(0).click()
    await expect(title).toHaveValue('Edited second source')
    await expectFade(motion)
    expect(await originalEditor.evaluate(element => element.isConnected)).toBe(true)
    await expect.poll(() => h.rpc<{ title: string }[]>('research/list'))
      .toEqual(expect.arrayContaining([expect.objectContaining({ title: 'Edited second source' })]))
    await motion.evaluate(control => control.stop())
  } finally {
    await h.close()
  }
})

test('Calendar modes fade and go-to disclosure closes inert with keyboard focus restored', async () => {
  const h = await launchApp('nl-calendar-motion-')
  try {
    await h.page.emulateMedia({ reducedMotion: 'no-preference' })
    await seedBook(h, { Opening: ['Arrival'] })
    await dismissTour(h.page)
    await h.page.evaluate(() => window.novalistStores.shell.getState().setMainView('calendar'))
    const view = h.page.locator('.calendar')
    await expect(view.locator('.calendar-month')).toBeVisible()
    await expect.poll(() => view.evaluate(element => element.getAnimations({ subtree: true }).length)).toBe(0)
    const motion = await holdMotion(h.page, '.calendar')
    await view.getByRole('button', { name: 'Week', exact: true }).click()
    await expect(view.locator('.calendar-week-grid')).toBeVisible()
    await expectFade(motion)
    const open = view.getByRole('button', { name: 'Go to date', exact: true })
    await open.click()
    const input = view.getByRole('textbox', { name: 'Go to date', exact: true })
    await expect(input).toBeFocused()
    await expectFade(motion)
    await input.press('Escape')
    const presence = view.locator('[data-motion-presence]').filter({ has: h.page.locator('#calendar-go-to') })
    await expect(presence).toHaveAttribute('data-motion-presence', 'closing')
    await expect(presence).toHaveAttribute('inert', '')
    await expect(open).toBeFocused()
    await expectFade(motion)
    await expect(view.locator('#calendar-go-to')).toHaveCount(0)
    await motion.evaluate(control => control.stop())
    await h.page.emulateMedia({ reducedMotion: 'reduce' })
    await view.getByRole('button', { name: 'Year', exact: true }).click()
    await expect(view.locator('.calendar-year')).toBeVisible()
    expect(await view.evaluate(element => element.getAnimations({ subtree: true }).length)).toBe(0)
  } finally {
    await h.close()
  }
})

